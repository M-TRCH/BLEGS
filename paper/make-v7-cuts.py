    global doc
    rows = [m for m in re.finditer(r'<w:tr[ >].*?</w:tr>', doc, re.S)
            if ptext(re.search(r'<w:tc>.*?</w:tc>', m.group(0), re.S).group(0)).startswith(first_cell_prefix)]
    if not rows:
        sys.exit('no table rows start with %r' % first_cell_prefix)
    for m in reversed(rows):
        doc = doc[:m.start()] + doc[m.end():]
    return len(rows)


