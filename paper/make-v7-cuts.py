BLOCK_RE = re.compile(r'<w:tbl>.*?</w:tbl>|<w:p(?:\s[^>]*)?/>|<w:p(?:\s[^>]*[^/])?>.*?</w:p>', re.S)
MATH_RE = re.compile(r'<m:oMath>.*?</m:oMath>', re.S)
EM = ' '


def ptext(p):
    return ''.join(re.findall(r'<(?:w|m):t(?: [^>]*)?>([^<]*)</(?:w|m):t>', p))


def body_text(p):
    return re.sub(r'\s+', ' ', ptext(MATH_RE.sub('', p))).lstrip(EM + ' ')


def find(prefix, what=None):
    hits = [m for m in BLOCK_RE.finditer(doc)
            if not m.group(0).startswith('<w:tbl') and body_text(m.group(0)).startswith(prefix)]
    if len(hits) != 1:
        sys.exit('%s: %d paragraphs start with %r' % (what or 'edit', len(hits), prefix[:40]))
    return hits[0]


def esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def text_run(s):
    # the combining macron of k-bar has no glyph in TH Sarabun New; v5 sets it in Arial
    if '̄' in s:
        a, b = s.split('̄', 1)
        return text_run(a) + ('<w:r><w:rPr><w:rFonts w:ascii="Arial" w:hAnsi="Arial" w:cs="Arial"/></w:rPr>'
                              '<w:t>̄</w:t></w:r>') + (text_run(b) if b else '')
    cs = '<w:cs/>' if re.search('[฀-๿]', s) else ''
    return '<w:r>%s<w:t xml:space="preserve">%s</w:t></w:r>' % ('<w:rPr>%s</w:rPr>' % cs if cs else '', esc(s))


def rewrite(prefix, new, allow_drop=False):
    """Replace the text of one paragraph, keeping its pPr and its maths
    (in order; a maths object may be dropped only with allow_drop)."""
    global doc
    m = find(prefix)
    p = m.group(0)
    maths = MATH_RE.findall(p)
    used = [int(k) for k in re.findall(r'\{(\d+)\}', new)]
    if used != sorted(set(used)) or (not allow_drop and used != list(range(len(maths)))) \
            or any(k >= len(maths) for k in used):
        sys.exit('%r: paragraph has %d maths, new text uses %s' % (prefix[:30], len(maths), used))
    ppr = re.search(r'<w:pPr>.*?</w:pPr>', p, re.S)
    head = re.match(r'<w:p(?:\s[^>]*)?>', p).group(0)
    lead = EM if ptext(p).startswith(EM) else ''
    out = []
    for i, piece in enumerate(re.split(r'\{(\d+)\}', lead + new)):
        if i % 2:
            out.append(maths[int(piece)])
        elif piece:
            out.append(text_run(piece))
    doc = doc[:m.start()] + head + (ppr.group(0) if ppr else '') + ''.join(out) + '</w:p>' + doc[m.end():]


def is_blank(block):
    return not block.startswith('<w:tbl') and not ptext(block).strip() and '<w:drawing' not in block \
        and '<m:oMath' not in block and 'w:sectPr' not in block


def delete(prefix):
    global doc
    m = find(prefix)
    doc = doc[:m.start()] + doc[m.end():]


def delete_table(caption_prefix):
    """Caption, table, and the blank line the build put under it."""
    global doc
    cap = find(caption_prefix, 'table caption')
    tbl = BLOCK_RE.match(doc, cap.end())
    if not tbl or not tbl.group(0).startswith('<w:tbl'):
        sys.exit('no table after %r' % caption_prefix)
    end = tbl.end()
    nxt = BLOCK_RE.match(doc, end)
    if nxt and is_blank(nxt.group(0)):
        end = nxt.end()
    doc = doc[:cap.start()] + doc[end:]


def delete_figure(caption_prefix):
    """Picture paragraph, empty lines, caption, blank line under it."""
    global doc
    cap = find(caption_prefix, 'figure caption')
    pics = [m for m in BLOCK_RE.finditer(doc, 0, cap.start()) if '<wp:inline' in m.group(0)]
    pic = pics[-1]
    between = doc[pic.end():cap.start()]
    if ptext(between).strip():
        sys.exit('text between picture and caption %r' % caption_prefix)
    end = cap.end()
    nxt = BLOCK_RE.match(doc, end)
    if nxt and is_blank(nxt.group(0)):
        end = nxt.end()
    doc = doc[:pic.start()] + doc[end:]


def renumber(label, old, new):
    """'ตารางที่ 4' -> 'ตารางที่ 2' everywhere (captions and text), in run text only."""
    global doc
    pat = re.compile(r'(<w:t(?: [^>]*)?>[^<]*?%s\s*)%d(?!\d)' % (label, old))
    doc, n = pat.subn(lambda g: g.group(1) + str(new), doc)
    # caption labels are split "ตารางที่ 4" in one run; text refs may be split "ตารางที่ " + "4 "
    split = re.compile(r'(<w:t(?: [^>]*)?>[^<]*%s\s*</w:t></w:r>\s*<w:r(?:\s[^>]*)?>(?:<w:rPr>.*?</w:rPr>)?'
                       r'<w:t(?: [^>]*)?>)%d(?!\d)' % (label, old), re.S)
    doc, n2 = split.subn(lambda g: g.group(1) + str(new), doc)
    return n + n2


